import assert from 'node:assert/strict';
import { readFile,stat,writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import path from 'node:path';
const require=createRequire(path.resolve('desktop/package.json'));
const asar=require('@electron/asar');
const directory='dist/windows/win-unpacked/resources';
const archive=path.join(directory,'app.asar');
const paths=asar.listPackage(archive);
for(const name of ['main.cjs','preload.cjs','service.mjs','policy.cjs'])assert(paths.includes('/'+name),name);
const preload=asar.extractFile(archive,'preload.cjs').toString();
assert(preload.includes('contextBridge.exposeInMainWorld'));
assert(!preload.includes('exposeInMainWorld(\'ipcRenderer\''));
const html=await readFile(path.join(directory,'service/web/app/index.html'),'utf8');
assert(html.includes("dataset.devEdition='desktop'"));
assert(html.includes("window.dashboardNavigation.register('remote'"));
assert(!html.includes('LOCAL TEST · MOCK DATA'));
assert(!html.includes('mock-key-for-layout-only'));
const vendor=JSON.parse(await readFile('desktop/vendor.json','utf8')).cloudflared;
const cloudflared=await readFile(path.join(directory,'desktop-assets/cloudflared.exe'));
assert.equal(createHash('sha256').update(cloudflared).digest('hex'),vendor.sha256);
assert((await readFile(path.join(directory,'desktop-assets/cloudflared-LICENSE.txt'),'utf8')).includes('Apache'));
await stat(path.join(directory,'service/node_modules/ws/package.json'));
const version=JSON.parse(await readFile('package.json','utf8')).version;
const executable=`dist/windows/SmartCharging-${version}-Windows-x64.exe`;
const bytes=await readFile(executable);
assert.equal(bytes.subarray(0,2).toString(),'MZ');assert(bytes.length>10_000_000);
const digest=createHash('sha256').update(bytes).digest('hex');
await writeFile(executable+'.sha256',`${digest}  ${path.basename(executable)}\n`);
console.log('Portable Windows package contains the desktop IPC, complete service, correct interface, verified tunnel executable and licence. Native Windows execution remains unverified.');
