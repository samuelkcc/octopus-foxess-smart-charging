import assert from 'node:assert/strict';
import { mkdtemp, readFile, readdir, rm, writeFile, stat } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {gunzipSync} from 'node:zlib';
import { CompactHistory } from '../linux/history.mjs';

const directory = await mkdtemp(path.join(os.tmpdir(), 'octopus-history-'));
let clock = Date.parse('2026-10-26T12:00:00Z');
const healthySpace=async()=>({freeBytes:20*1024**3,totalBytes:32*1024**3});
const make = () => new CompactHistory({ directory, now: () => clock,diskSpace:healthySpace });
const sample = (values, at = clock) => ({ updatedAt: new Date(at).toISOString(), values });
try {
  let history = make();
  assert.equal((await history.getSettings()).retentionMonths,12);
  for (const value of [0,25,1.5,'12',null]) await assert.rejects(history.setRetentionMonths(value),{statusCode:400});
  assert.equal(await history.record(sample({ loadsPower: 2, SoC: 50 })), true);
  assert.equal(await history.record(sample({ loadsPower: 100 })), false, 'Cached/duplicate readings do not inflate the average');
  clock += 60_000;
  await history.record(sample({ loadsPower: 4, pvPower: 0, SoC: 60 }));
  let report = await history.readMonth('2026-10');
  assert.equal(report.points[0].values.loadsPower, 3);
  assert.equal(report.points[0].values.SoC, 55);
  assert.equal(report.points[0].values.pvPower, 0, 'A real zero remains a zero');
  assert.equal(report.points[0].values.feedinPower, null, 'Missing fields are not invented as zeros');
  assert.equal(report.points[0].samples.loadsPower, 2);
  await history.close();
  history = make();
  assert.equal(await history.record(sample({ loadsPower: 9 })), false, 'Restart retains the last accepted sample minute');
  clock += 30 * 60_000;
  assert.equal(await history.record(sample({ loadsPower: 1 }, clock - 5 * 60_000)), false, 'Stale data is not re-dated');
  await history.record(sample({ loadsPower: 1 }));
  report = await history.readMonth('2026-10');
  assert.equal(report.points.length, 2, 'Downtime stays a gap, without synthetic intervals');
  assert.equal(report.points[1].at, '2026-10-26T12:30:00.000Z');
  await history.recordEvent({at:new Date(clock).toISOString(),type:'automation_paused',until:null,revision:1});
  assert.equal((await history.readMonth('2026-10')).events[0].type,'automation_paused');
  await history.setRetentionMonths(24);
  await history.close();
  const archive = path.join(directory, '2026-10.jsonl');
  assert.equal((await stat(archive+'.gz')).mode & 0o777,0o600,'Compressed archives remain owner-only');
  const firstRow = gunzipSync(await readFile(archive+'.gz')).toString().trim();
  assert.ok((await readFile(archive+'.gz')).length<Buffer.byteLength(firstRow),'Monthly gzip uses less space than expanded rows');
  await writeFile(archive, `${firstRow}\n${firstRow}\n{incomplete\n`);
  history = make();
  assert.equal((await history.getSettings()).retentionMonths,24,'Retention survives restart');
  assert.equal((await history.readMonth('2026-10')).points.length, 2, 'Duplicate crash appends and incomplete rows are handled');
  await assert.rejects(history.readMonth('../../config'), { statusCode:400 });
  await assert.rejects(history.readMonth('2026-13'), { statusCode:400 });
  await writeFile(path.join(directory, '2024-09.jsonl'), `${firstRow}\n`);
  await writeFile(path.join(directory, '2024-10.jsonl'), `${firstRow}\n`);
  await history.readMonth('2026-10');
  assert.ok(!(await readdir(directory)).includes('2024-09.jsonl'), 'Expired month archives are deleted');
  clock = Date.parse('2028-11-01T00:00:00Z');
  assert.equal((await history.readMonth('2026-10')).points.length, 0, 'Data older than 24 calendar months is unavailable');
  assert.ok(!(await readdir(directory)).includes('2026-10.jsonl'));
  assert.ok(!(await readdir(directory)).includes('2026-10.jsonl.gz'));
  assert.equal((await history.readMonth('2026-10')).events.length,0,'Expired activity is erased too');
  clock = Date.parse('2028-03-31T12:00:00Z');
  await history.setRetentionMonths(1);
  assert.equal((await history.getSettings()).cutoff,'2028-02-29T12:00:00.000Z','Calendar month retention clamps leap days');
  clock = Date.parse('2027-03-31T12:00:00Z');
  assert.equal((await history.getSettings()).cutoff,'2027-02-28T12:00:00.000Z');
  const before = [Math.floor(Date.parse('2027-02-27T12:00:00Z')/60000),...Array(7).fill(1000),...Array(7).fill(1)];
  const after = [Math.floor(Date.parse('2027-03-01T12:00:00Z')/60000),...Array(7).fill(1000),...Array(7).fill(1)];
  await history.setRetentionMonths(12);
  await writeFile(path.join(directory,'2027-02.jsonl'),JSON.stringify(before)+'\n');
  await writeFile(path.join(directory,'2027-03.jsonl'),JSON.stringify(after)+'\n');
  await history.setRetentionMonths(1);
  assert.equal((await history.readMonth('2027-02')).points.length,0,'Shorter policy erases boundary rows');
  assert.equal((await history.readMonth('2027-03')).points.length,1,'Newer records survive shorter policy');
  assert.equal((await readFile(path.join(directory,'2027-02.jsonl'),'utf8')).trim(),'');
  const bufferedDirectory=path.join(directory,'buffered');
  clock=Date.parse('2026-10-26T12:00:00Z');
  const buffered=new CompactHistory({directory:bufferedDirectory,now:()=>clock,diskSpace:healthySpace});
  assert.equal((await buffered.getSettings()).saveIntervalMinutes,60);
  for(const invalid of [0,5,29,45,120,'30',null])await assert.rejects(buffered.setSettings({saveIntervalMinutes:invalid}),{statusCode:400});
  for(let slot=0;slot<4;slot++){
    clock=Date.parse('2026-10-26T12:00:00Z')+slot*15*60000;
    await buffered.record(sample({loadsPower:slot+1,batChargePower:0,batDischargePower:0}));
  }
  const memoryReport=await buffered.readMonth('2026-10');
  assert.equal(memoryReport.points.length,4,'Completed buffered intervals stay visible before disk save');
  assert.equal(memoryReport.bufferedIntervals,4);
  assert.equal(memoryReport.storageBytes,0,'Routine readings do not create files before the hourly save');
  const abruptRestart=new CompactHistory({directory:bufferedDirectory,now:()=>clock,diskSpace:healthySpace});
  assert.equal((await abruptRestart.readMonth('2026-10')).points.length,0,'Sudden power loss can lose the documented unsaved buffer');
  clock=Date.parse('2026-10-26T13:00:00Z');
  await buffered.flushIfDue();
  assert.equal((await buffered.getSettings()).bufferedIntervals,0,'The clock flushes data even without another telemetry update');
  const resumed=new CompactHistory({directory:bufferedDirectory,now:()=>clock,diskSpace:healthySpace});
  assert.equal((await resumed.readMonth('2026-10')).points.length,4,'An hourly batch survives restart');
  assert.ok((await resumed.getSettings()).allocatedBytes>0);
  await resumed.setSettings({saveIntervalMinutes:30});
  clock+=15*60000;await resumed.record(sample({loadsPower:8}));
  assert.equal((await resumed.getSettings()).bufferedIntervals,2,'The pending archive slot and new current slot stay in RAM until the next save');
  clock+=15*60000;await resumed.flushIfDue();
  const reloaded=new CompactHistory({directory:bufferedDirectory,now:()=>clock,diskSpace:healthySpace});
  assert.equal((await reloaded.getSettings()).saveIntervalMinutes,30,'Save policy survives restart');
  assert.equal((await reloaded.readMonth('2026-10')).points.length,5,'The 30-minute option saves buffered readings');
  await writeFile(path.join(bufferedDirectory,'preferences.json'),JSON.stringify({v:1,retentionMonths:12}));
  const legacy=new CompactHistory({directory:bufferedDirectory,now:()=>clock,diskSpace:healthySpace});
  assert.equal((await legacy.getSettings()).saveIntervalMinutes,60,'Existing installations migrate to hourly saves');
  const lowDirectory=path.join(directory,'low-space');
  let freeBytes=3*1024**3;
  const low=new CompactHistory({directory:lowDirectory,now:()=>clock,diskSpace:async()=>({freeBytes,totalBytes:32*1024**3})});
  await low.getSettings();
  const makeRow=at=>JSON.stringify([Math.floor(Date.parse(at)/60000),...Array(7).fill(1000),...Array(7).fill(1)]);
  await writeFile(path.join(lowDirectory,'2026-09.jsonl'),makeRow('2026-09-01T00:00:00Z')+'\n');
  await writeFile(path.join(lowDirectory,'2026-10.jsonl'),makeRow('2026-10-24T00:00:00Z')+'\n'+makeRow('2026-10-26T13:00:00Z')+'\n');
  await low.cleanup();
  assert.equal((await low.getSettings()).lowStorage,true,'The warning stays active when other files keep disk space below 4 GB');
  assert.ok(!(await readdir(lowDirectory)).includes('2026-09.jsonl'),'Oldest saved history is removed before the configured retention');
  assert.equal((await low.readMonth('2026-10')).points.length,1,'The newest 24 hours are preserved under disk pressure');
  freeBytes=8*1024**3;await low.cleanup();
  assert.equal((await low.getSettings()).lowStorage,false,'The warning recovers when free space returns');
  await low.setSettings({retentionMonths:3});
  await low.record(sample({loadsPower:1}));
  await low.recordEvent({at:new Date(clock).toISOString(),type:'automation_paused',until:null,revision:9});
  await writeFile(path.join(lowDirectory,'unrelated.txt'),'keep');
  await low.clearAll();
  assert.equal((await low.readMonth('2026-10')).points.length,0);
  assert.equal((await low.readMonth('2026-10')).events.length,0);
  assert.equal((await low.getSettings()).bufferedIntervals,0,'Clear history also clears the RAM buffer');
  assert.equal((await low.getSettings()).retentionMonths,3,'Clear history preserves preferences');
  assert.equal(await readFile(path.join(lowDirectory,'unrelated.txt'),'utf8'),'keep','Clear only removes recognised history files');
  await low.close();
  const afterClear=new CompactHistory({directory:lowDirectory,now:()=>clock,diskSpace:healthySpace});
  assert.equal((await afterClear.readMonth('2026-10')).points.length,0,'Cleared buffers do not return after shutdown and restart');
  console.log('History averages, missing values, cache deduplication, restart persistence, outage gaps, crash recovery, query validation, 24-month retention, RAM buffering, hourly/half-hourly saves, power-loss limits, and save-policy migration, compression, low-space eviction, and explicit clearing passed.');
} finally { await rm(directory, { recursive:true, force:true }); }
